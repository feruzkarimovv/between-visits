import { AudioLines, FlaskConical, Layers, type LucideIcon } from "lucide-react";
import type { DataOrigin } from "@/lib/types";
import { cn } from "./ui/primitives";

/**
 * `data_origin` badge for every Site Signal view, row, episode and query (docs/03 §5.1, docs/06 § Site
 * Signal pages, docs/10 §7.4, REQ-030). Neutral slate ink; the outline carries the meaning, the text says it:
 *   SIMULATED dashed outline · MEASURED solid outline · MIXED half dashed, half solid.
 */

const ORIGIN: Record<DataOrigin, { icon: LucideIcon; title: string }> = {
  SIMULATED: {
    icon: FlaskConical,
    title: "SIMULATED: generated by the monitoring simulation from its pre-registered parameters. Not real site data.",
  },
  MEASURED: {
    icon: AudioLines,
    title: "MEASURED: computed from calls processed by the app's real handlers (live or replayed calls), not from the simulation.",
  },
  MIXED: {
    icon: Layers,
    title: "MIXED: shows both SIMULATED and MEASURED episodes. They are listed together but never pooled in a statistic.",
  },
};

const BASE = "inline-flex items-center gap-1 border bg-white py-0.5 text-sm leading-5 font-semibold tracking-wide whitespace-nowrap text-slate-800";

export function DataOriginBadge({ origin, className }: { origin: DataOrigin; className?: string }) {
  const meta = ORIGIN[origin];
  if (!meta) {
    // Unknown value from the API: show it as is, dashed, never styled as MEASURED.
    return <span className={cn(BASE, "rounded-full border-dashed border-slate-500 px-2", className)}>{origin}</span>;
  }
  const Icon = meta.icon;

  if (origin === "MIXED") {
    // Half dashed: the icon segment is dashed, the label segment solid.
    return (
      <span className={cn("inline-flex items-stretch", className)} title={meta.title} data-origin={origin}>
        <span className={cn(BASE, "rounded-l-full border-r-0 border-dashed border-slate-500 pr-1 pl-2")}>
          <Icon className="size-3.5" aria-hidden />
        </span>
        <span className={cn(BASE, "rounded-r-full border-l-0 border-solid border-slate-500 pr-2 pl-0.5")}>{origin}</span>
      </span>
    );
  }

  return (
    <span
      className={cn(
        BASE,
        "rounded-full border-slate-500 px-2",
        origin === "SIMULATED" ? "border-dashed" : "border-solid",
        className,
      )}
      title={meta.title}
      data-origin={origin}
    >
      <Icon className="size-3.5" aria-hidden />
      {origin}
    </span>
  );
}
